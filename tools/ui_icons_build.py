#!/usr/bin/env python3
"""Compile the Lucide SVGs in assets/ui/icons/ into scenes/ui/ui_icon_data.gd.

    python tools/ui_icons_build.py

Why a generated script instead of importing the SVGs: Godot rasterises an
imported SVG once at a fixed size, and Lucide strokes with `currentColor`,
which the importer turns black. Keeping the markup as data lets UiIcons
render each icon at the exact pixel size asked for, in white (so a Button's
icon modulate tints it), and ships in exports without extra filters.

Add an icon: drop <name>.svg (from lucide-static, same version — see
CREDITS.md) into assets/ui/icons/ and re-run. Stdlib only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "assets" / "ui" / "icons"
OUT = REPO / "scenes" / "ui" / "ui_icon_data.gd"


def inner_markup(svg: str) -> str:
    """The drawing elements between <svg ...> and </svg>, whitespace-collapsed."""
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not m:
        raise ValueError("no <svg> element")
    body = re.sub(r"<!--.*?-->", "", m.group(1), flags=re.S)
    body = re.sub(r"\s+", " ", body).strip()
    return body.replace(" />", "/>")


def main() -> int:
    names = sorted(p.stem for p in SRC.glob("*.svg"))
    if not names:
        print("ui_icons_build: no SVGs in", SRC, file=sys.stderr)
        return 1
    lines = [
        "class_name UiIconData",
        "extends RefCounted",
        "",
        "## GENERATED by tools/ui_icons_build.py from assets/ui/icons/ (Lucide,",
        "## ISC — see CREDITS.md). Do not edit; add an SVG and re-run the tool.",
        "## Each value is the inner markup of a 24×24 Lucide icon; UiIcons wraps",
        "## it in an <svg> with a white stroke and rasterises it at the size asked.",
        "",
        "const ICONS := {",
    ]
    for n in names:
        body = inner_markup((SRC / f"{n}.svg").read_text(encoding="utf-8"))
        if '"' in body.replace('\\"', ""):
            body = body.replace('"', "'")
        lines.append(f'\t"{n}": "{body}",')
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"ui_icons_build: {len(names)} icons -> {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
